const PDFDocument = require('pdfkit');
// NOTE: MySQL removal is in progress; this handler is still using MySQL queries via pool placeholder.
const { pool } = require('../config/db');

async function getStudentProfile(req, res, next) {
  try {
    const [rows] = await pool.query(`SELECT id, name, email, department_id FROM students WHERE id = ?`, [req.user.userId]);
    if (!rows.length) return res.status(404).json({ success: false, error: 'Student not found' });
    res.json({ success: true, student: rows[0] });
  } catch (e) {
    next(e);
  }
}

async function getAttendance(req, res, next) {
  try {
    const [rows] = await pool.query(
      `
      SELECT a.id, a.course_id, a.subject_id, a.attendance_date, a.status
      FROM attendance a
      WHERE a.student_id = ?
      ORDER BY a.attendance_date DESC
      LIMIT 50
      `,
      [req.user.userId]
    );

    res.json({ success: true, attendance: rows });
  } catch (e) {
    next(e);
  }
}

async function getNotices(req, res, next) {
  try {
    const [rows] = await pool.query(`SELECT * FROM notices ORDER BY created_at DESC LIMIT 30`);
    res.json({ success: true, notices: rows });
  } catch (e) {
    next(e);
  }
}

async function getResults(req, res, next) {
  try {
    const [rows] = await pool.query(
      `
      SELECT r.*, c.name as course_name
      FROM results r
      LEFT JOIN courses c ON c.id = r.course_id
      WHERE r.student_id = ?
      ORDER BY r.semester, r.course_id
      `,
      [req.user.userId]
    );
    res.json({ success: true, results: rows });
  } catch (e) {
    next(e);
  }
}

async function getFeeStatus(req, res, next) {
  try {
    const [rows] = await pool.query(
      `SELECT f.* FROM fees f WHERE f.student_id = ? ORDER BY f.id DESC LIMIT 10`,
      [req.user.userId]
    );
    res.json({ success: true, fees: rows });
  } catch (e) {
    next(e);
  }
}

async function getRoutine(req, res, next) {
  try {
    const [rows] = await pool.query(
      `
      SELECT r.*
      FROM class_routine r
      WHERE r.department_id = (SELECT department_id FROM students WHERE id = ?)
      ORDER BY r.day_of_week, r.start_time
      `,
      [req.user.userId]
    );
    res.json({ success: true, routine: rows });
  } catch (e) {
    next(e);
  }
}

async function downloadIdCard(req, res, next) {
  try {
    const [rows] = await pool.query(`SELECT name, email, department_id FROM students WHERE id = ?`, [req.user.userId]);
    if (!rows.length) return res.status(404).json({ success: false, error: 'Student not found' });

    const student = rows[0];

    // PDF
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', 'attachment; filename="ID_CARD.pdf"');

    const doc = new PDFDocument({ margin: 30 });
    doc.pipe(res);

    doc.fontSize(20).text('Smart College Management System', { align: 'center' });
    doc.moveDown();
    doc.fontSize(16).text('Student ID Card', { align: 'center' });
    doc.moveDown(2);

    doc.fontSize(12).text(`Name: ${student.name}`);
    doc.text(`Email: ${student.email}`);
    doc.text(`Department ID: ${student.department_id}`);

    doc.moveDown();
    doc.fontSize(10).fillColor('gray').text('Generated by the system.', { align: 'center' });

    doc.end();
  } catch (e) {
    next(e);
  }
}

module.exports = { getStudentProfile, getAttendance, getNotices, getResults, getFeeStatus, downloadIdCard, getRoutine };

